// Turns each built app folder into an installable, offline-capable PWA:
//   icons (PNG via sharp) · manifest.webmanifest · sw.js with a precache list · head tags,
// then moves it to its unlisted path when DELIVERY_SALT is set.
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import sharp from 'sharp'
import { deliverySuffix } from './delivery-suffix.mjs'

const DIST = 'dist'
const apps = JSON.parse(readFileSync('src/shared/apps.json', 'utf8'))
const glyphs = JSON.parse(readFileSync('src/shared/glyphs.json', 'utf8'))
const salt = process.env.DELIVERY_SALT ?? ''
const publicKey = JSON.parse(readFileSync('src/config/license-public-key.json', 'utf8'))

if (!publicKey) console.warn('⚠  No activation public key - run `npm run keygen`. Apps will stay locked.')
if (!salt) console.warn('⚠  DELIVERY_SALT not set - apps are published at guessable /apps/<slug>/ paths.')

/** Icon art: rounded square in the app colour, white glyph, ball accent. `pad` shrinks art for maskable icons. */
function iconSvg(app, { rounded = true, pad = 0 } = {}) {
  const s = 48 - pad * 2
  const k = s / 48
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48">
  <rect width="48" height="48" rx="${rounded ? 11 : 0}" fill="${app.color}"/>
  <g transform="translate(${pad} ${pad}) scale(${k})">
    <g transform="translate(12 12)" fill="none" stroke="#fff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="${glyphs[app.glyph]}"/></g>
    <circle cx="39" cy="9" r="4" fill="#d9f02b"/>
  </g>
</svg>`
}

async function png(svg, size, out) {
  await sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png().toFile(out)
}

const swSource = (slug, version, precache) => `// Generated by scripts/postbuild.mjs - do not edit.
const PREFIX = 'pt-${slug}-'
const CACHE = PREFIX + '${version}'
const PRECACHE = ${JSON.stringify(precache, null, 2)}
const INDEX = new URL('./index.html', self.registration.scope).href

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

function timeout(ms) {
  return new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms))
}

self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return

  // Pages: network first so updates arrive, cached copy when offline or on a slow connection.
  if (req.mode === 'navigate') {
    event.respondWith(
      Promise.race([fetch(req), timeout(4000)])
        .then((res) => {
          if (res.ok) caches.open(CACHE).then((c) => c.put(INDEX, res.clone()))
          return res
        })
        .catch(() => caches.match(INDEX).then((r) => r || Response.error())),
    )
    return
  }

  // Hashed assets and icons: cache first.
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && res.type === 'basic') {
            const copy = res.clone()
            caches.open(CACHE).then((c) => c.put(req, copy))
          }
          return res
        }),
    ),
  )
})
`

for (const app of apps) {
  const dir = join(DIST, 'apps', app.slug)
  const htmlPath = join(dir, 'index.html')
  if (!existsSync(htmlPath)) throw new Error(`Missing build output for ${app.slug}`)

  await png(iconSvg(app), 192, join(dir, 'icon-192.png'))
  await png(iconSvg(app), 512, join(dir, 'icon-512.png'))
  await png(iconSvg(app, { rounded: false, pad: 7 }), 512, join(dir, 'icon-maskable-512.png'))
  await png(iconSvg(app, { rounded: false }), 180, join(dir, 'apple-touch-icon.png'))

  const manifest = {
    id: './',
    name: app.name,
    short_name: app.shortName,
    description: app.description,
    start_url: './',
    scope: './',
    display: 'standalone',
    orientation: 'any',
    background_color: '#f7f8f3',
    theme_color: app.color,
    categories: ['sports', 'utilities'],
    icons: [
      { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  }
  writeFileSync(join(dir, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2))

  let html = readFileSync(htmlPath, 'utf8')
  const head = [
    '<link rel="manifest" href="./manifest.webmanifest" />',
    '<link rel="icon" href="./icon-192.png" type="image/png" />',
    '<link rel="apple-touch-icon" href="./apple-touch-icon.png" />',
    '<meta name="mobile-web-app-capable" content="yes" />',
    '<meta name="apple-mobile-web-app-capable" content="yes" />',
    '<meta name="apple-mobile-web-app-status-bar-style" content="default" />',
    `<meta name="apple-mobile-web-app-title" content="${app.shortName}" />`,
  ].join('\n    ')
  html = html.replace('</head>', `    ${head}\n  </head>`)
  writeFileSync(htmlPath, html)

  // Everything the page loads up front (entry, modulepreloaded chunks, CSS) is in its HTML.
  const assets = [...html.matchAll(/(?:src|href)="([^"]*\/assets\/[^"]+)"/g)].map((m) => m[1])
  // Fonts are referenced from the CSS, not the HTML. Precache the Latin subsets (English,
  // Filipino and the ₱ sign); browsers only fetch the other subsets for other scripts.
  for (const css of assets.filter((a) => a.endsWith('.css'))) {
    const text = readFileSync(join(DIST, 'assets', css.split('/assets/')[1]), 'utf8')
    for (const [, raw] of text.matchAll(/url\(([^)]+?latin[^)]*?\.woff2)\)/g)) {
      const font = raw.replace(/^["']|["']$/g, '')
      // Vite writes absolute (base-prefixed) URLs; resolve anything relative against the CSS file.
      assets.push(font.startsWith('/') ? font : css.replace(/[^/]+\.css$/, font.replace(/^\.\//, '')))
    }
  }
  const precache = ['./', './index.html', './manifest.webmanifest', './icon-192.png', './icon-512.png', './apple-touch-icon.png', ...new Set(assets)]
  const version = createHash('sha256').update(precache.join('|')).digest('hex').slice(0, 12)
  writeFileSync(join(dir, 'sw.js'), swSource(app.slug, version, precache))

  const target = join(DIST, 'apps', `${app.slug}${deliverySuffix(salt, app.slug)}`)
  if (target !== dir) {
    rmSync(target, { recursive: true, force: true })
    renameSync(dir, target)
  }
  console.log(`✓ ${app.name.padEnd(26)} → /${target.replace(/\\/g, '/').replace(/^dist\//, '')}/  (${assets.length} precached assets)`)
}
